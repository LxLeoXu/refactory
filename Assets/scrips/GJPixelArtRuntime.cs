using System;
using System.Collections.Generic;
using System.Reflection;
using UnityEngine;
using UnityEngine.InputSystem;

// One optional visual layer. It never changes damage, movement, inventory or boss AI.
// Installed on Player via Tools > GameJam > Apply Pixel Art To Game.
[DisallowMultipleComponent]
public class GJPixelArtRuntime : MonoBehaviour
{
    [Header("Pixel Art - visual only")]
    public bool styleMiniTurrets = true;
    public bool styleForgeHeart = true;
    public bool showEquippedFactoryWeapon = true;
    public bool styleItemPickups = true;
    public bool decorateDungeon = true;
    [Range(0, 4)] public int propsPerRoom = 2;

    float nextScan;
    Component weaponComponent;
    FieldInfo equippedField;
    Transform gun;
    SpriteRenderer gunRenderer;
    readonly HashSet<int> seenBullets = new HashSet<int>();
    readonly Dictionary<int, float> turretShotUntil = new Dictionary<int, float>();
    readonly Dictionary<string, Sprite> cache = new Dictionary<string, Sprite>();

    Sprite Art(string name)
    {
        Sprite result;
        if (!cache.TryGetValue(name, out result))
        {
            result = Resources.Load<Sprite>("GJPixelArt/" + name);
            cache[name] = result;
        }
        return result;
    }

    void Awake()
    {
        weaponComponent = GetComponent("FactoryWeapons");
        if (weaponComponent != null)
            equippedField = weaponComponent.GetType().GetField("equipped", BindingFlags.Public | BindingFlags.Instance);
    }

    void Update()
    {
        if (Time.time >= nextScan)
        {
            nextScan = Time.time + 0.22f;
            RefreshVisuals();
        }
        UpdateWeaponVisual();
    }

    void RefreshVisuals()
    {
        MonoBehaviour[] scripts = FindObjectsByType<MonoBehaviour>(FindObjectsSortMode.None);
        List<MonoBehaviour> turrets = new List<MonoBehaviour>();
        List<MonoBehaviour> bullets = new List<MonoBehaviour>();

        foreach (MonoBehaviour script in scripts)
        {
            if (script == null) continue;
            string className = script.GetType().Name;
            if (className == "GJFieldTurret" && styleMiniTurrets) turrets.Add(script);
            else if (className == "GJFieldTurretBullet" && styleMiniTurrets) bullets.Add(script);
            else if (className == "GJForgeHeartBoss" && styleForgeHeart) SkinBoss(script);
            else if (className == "ItemPickup" && styleItemPickups) SkinItem(script);
        }

        foreach (MonoBehaviour turret in turrets) SkinTurret(turret);
        foreach (MonoBehaviour bullet in bullets) SkinTurretBullet(bullet, turrets);
        foreach (MonoBehaviour turret in turrets)
        {
            Transform marker = turret.transform.Find("__GJ_PixelTurret");
            if (marker == null) continue;
            SpriteRenderer renderer = marker.GetComponent<SpriteRenderer>();
            if (renderer == null) continue;
            float time;
            bool shooting = turretShotUntil.TryGetValue(turret.GetInstanceID(), out time) && Time.time < time;
            Sprite selected = Art(shooting ? "turret_fire" : "turret_idle");
            if (selected != null) renderer.sprite = selected;
        }

        if (decorateDungeon && propsPerRoom > 0)
            foreach (Room room in FindObjectsByType<Room>(FindObjectsSortMode.None)) DecorateRoom(room);
    }

    void SkinTurret(MonoBehaviour turret)
    {
        if (turret.transform.Find("__GJ_PixelTurret") != null) return;
        Sprite image = Art("turret_idle");
        if (image == null) return;

        // Hide only the primitive SpriteRenderers generated by GJFieldTurret.
        foreach (SpriteRenderer old in turret.GetComponentsInChildren<SpriteRenderer>(true))
            old.enabled = false;

        GameObject go = new GameObject("__GJ_PixelTurret");
        go.transform.SetParent(turret.transform, false);
        go.transform.localPosition = new Vector3(0f, 0.08f, 0f);
        SpriteRenderer sr = go.AddComponent<SpriteRenderer>();
        sr.sprite = image;
        sr.sortingOrder = 15;
    }

    void SkinTurretBullet(MonoBehaviour bullet, List<MonoBehaviour> turrets)
    {
        Sprite image = Art("turret_bullet");
        SpriteRenderer renderer = bullet.GetComponent<SpriteRenderer>();
        if (image != null && renderer != null && renderer.sprite != image)
        {
            renderer.sprite = image;
            renderer.color = Color.white;
            renderer.sortingOrder = 16;
            bullet.transform.localScale = Vector3.one * 0.34f;
        }
        if (!seenBullets.Add(bullet.GetInstanceID())) return;
        // Display a brief muzzle flash when a new bullet appears near its turret.
        float best = 2.1f * 2.1f;
        MonoBehaviour closest = null;
        foreach (MonoBehaviour turret in turrets)
        {
            float d = ((Vector2)(turret.transform.position - bullet.transform.position)).sqrMagnitude;
            if (d < best) { best = d; closest = turret; }
        }
        if (closest != null) turretShotUntil[closest.GetInstanceID()] = Time.time + 0.2f;
    }

    void SkinBoss(MonoBehaviour boss)
    {
        SpriteRenderer sr = boss.GetComponent<SpriteRenderer>();
        if (sr == null) sr = boss.GetComponentInChildren<SpriteRenderer>();
        if (sr == null) return;
        float fraction = 1f;
        PropertyInfo property = boss.GetType().GetProperty("HealthFraction", BindingFlags.Instance | BindingFlags.Public);
        if (property != null && property.PropertyType == typeof(float))
        {
            object v = property.GetValue(boss, null);
            if (v is float) fraction = (float)v;
        }
        Sprite image = Art(fraction <= 0.5f ? "forge_heart_phase2" : "forge_heart_idle");
        if (image != null && sr.sprite != image) sr.sprite = image;
    }

    void SkinItem(MonoBehaviour pickup)
    {
        string[] fields = { "itemId", "itemID", "itemIdToGive" };
        string itemId = null;
        Type t = pickup.GetType();
        foreach (string name in fields)
        {
            FieldInfo field = t.GetField(name, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
            if (field != null && field.FieldType == typeof(string))
            { itemId = (string)field.GetValue(pickup); break; }
        }
        if (string.IsNullOrEmpty(itemId)) return;
        string normalized = itemId.Replace(" ", "_").ToLowerInvariant();
        string icon = null;
        if (normalized == "scrap") icon = "item_scrap";
        else if (normalized == "iron") icon = "item_iron";
        else if (normalized == "crystal") icon = "item_crystal";
        else if (normalized == "weapon_upgrade") icon = "item_weapon_upgrade";
        else if (normalized == "armor_upgrade") icon = "item_armor_upgrade";
        else if (normalized == "health_potion" || normalized == "potion") icon = "item_potion";
        if (icon == null) return;
        Sprite sprite = Art(icon);
        if (sprite == null) return;
        SpriteRenderer renderer = pickup.GetComponentInChildren<SpriteRenderer>();
        if (renderer == null) return;
        if (renderer.sprite != sprite) { renderer.sprite = sprite; renderer.color = Color.white; }
    }

    void UpdateWeaponVisual()
    {
        if (!showEquippedFactoryWeapon) { if (gunRenderer != null) gunRenderer.enabled = false; return; }
        if (weaponComponent == null)
        {
            weaponComponent = GetComponent("FactoryWeapons");
            if (weaponComponent != null)
                equippedField = weaponComponent.GetType().GetField("equipped", BindingFlags.Public | BindingFlags.Instance);
        }
        if (weaponComponent == null || equippedField == null) return;
        string equipped = equippedField.GetValue(weaponComponent).ToString();
        string spriteName = equipped == "ScrapShotgun" ? "scrap_shotgun" :
            equipped == "CrystalRifle" ? "crystal_rifle" :
            equipped == "FurnaceCannon" ? "furnace_cannon" : null;
        if (spriteName == null) { if (gunRenderer != null) gunRenderer.enabled = false; return; }
        Sprite art = Art(spriteName);
        if (art == null) return;

        if (gunRenderer == null)
        {
            GameObject go = new GameObject("__GJ_EquippedFactoryWeapon");
            go.transform.SetParent(transform, false);
            gun = go.transform;
            gunRenderer = go.AddComponent<SpriteRenderer>();
            gunRenderer.sortingOrder = 18;
        }
        gunRenderer.sprite = art;
        gunRenderer.enabled = true;
        Vector2 dir = Vector2.right;
        Camera cam = Camera.main;
        if (cam != null && Mouse.current != null)
        {
            Vector2 mouse = Mouse.current.position.ReadValue();
            Vector3 world = cam.ScreenToWorldPoint(new Vector3(mouse.x, mouse.y,
                Mathf.Abs(cam.transform.position.z - transform.position.z)));
            Vector2 delta = (Vector2)world - (Vector2)transform.position;
            if (delta.sqrMagnitude > 0.001f) dir = delta.normalized;
        }
        gun.position = transform.position + (Vector3)(dir * 0.43f);
        gun.rotation = Quaternion.Euler(0f, 0f, Mathf.Atan2(dir.y, dir.x) * Mathf.Rad2Deg);
        gunRenderer.flipY = dir.x < 0f;
        gun.localScale = Vector3.one * 0.72f;
    }

    void DecorateRoom(Room room)
    {
        if (room == null || room.transform.Find("__GJ_PixelDecor") != null) return;
        Sprite[] choices = { Art("prop_crate"), Art("prop_barrel"), Art("prop_crystal") };
        bool any = false;
        foreach (Sprite s in choices) if (s != null) { any = true; break; }
        if (!any) return;

        GameObject parent = new GameObject("__GJ_PixelDecor");
        parent.transform.SetParent(room.transform, false);
        Transform floor = room.transform.Find("Floor");
        Vector2 bounds = new Vector2(20f, 12f);
        if (floor != null)
        {
            SpriteRenderer floorSprite = floor.GetComponent<SpriteRenderer>();
            if (floorSprite != null) bounds = floorSprite.bounds.size;
        }
        float x = Mathf.Max(2f, bounds.x * 0.5f - 2.2f);
        float y = Mathf.Max(2f, bounds.y * 0.5f - 2.2f);
        Vector2[] corners = {
            new Vector2(-x, -y), new Vector2(x, y),
            new Vector2(-x, y), new Vector2(x, -y)
        };
        int seed = Mathf.Abs(room.gridPos.x * 31 + room.gridPos.y * 117 + 17);
        int offset = seed % 4;
        for (int i = 0; i < Mathf.Min(propsPerRoom, corners.Length); i++)
        {
            Sprite sprite = choices[(seed + i) % choices.Length];
            if (sprite == null) continue;
            GameObject prop = new GameObject("PixelProp_" + i);
            prop.transform.SetParent(parent.transform, false);
            prop.transform.localPosition = corners[(offset + i) % corners.Length];
            SpriteRenderer r = prop.AddComponent<SpriteRenderer>();
            r.sprite = sprite;
            r.sortingOrder = -3;
            // Intentionally no collider: dodging paths remain open.
        }
    }
}
